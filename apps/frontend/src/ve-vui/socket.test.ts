import assert from "node:assert/strict";
import { createServer } from "node:http";
import { test } from "node:test";
import { Server } from "socket.io";
import { io, type Socket } from "socket.io-client";
import { registerDrawingNamespace } from "./socket";
import type { Reply, RoomView, Session } from "./types";

test("real multi-client room flow, secret isolation, reconnect, permissions, and payload validation", async () => {
  const http = createServer();
  const server = new Server(http);
  const game = registerDrawingNamespace(server.of("/ve-vui"));
  const clients: Socket[] = [];
  await new Promise<void>(resolve => http.listen(0, "127.0.0.1", resolve));
  const address = http.address() as { port: number };
  const connect = () => new Promise<Socket>(resolve => {
    const socket = io(`http://127.0.0.1:${address.port}/ve-vui`, { transports: ["websocket"], forceNew: true });
    clients.push(socket); socket.once("connect", () => resolve(socket));
  });
  const request = (socket: Socket, event: string, payload: unknown = {}) => new Promise<Reply>((resolve, reject) => {
    socket.timeout(2000).emit(event, payload, (error: Error | null, response: Reply) => error ? reject(error) : resolve(response));
  });
  const states = new Map<string, RoomView>();
  try {
    const first = await connect();
    first.on("room:state", (view: RoomView) => states.set(first.id!, view));
    const created = await request(first, "room:create", { name: "Mẹ" });
    assert.equal(created.ok, true);
    const hostSession = created.session!;
    const second = await connect();
    second.on("room:state", (view: RoomView) => states.set(second.id!, view));
    const joined = await request(second, "room:join", { code: hostSession.code, name: "Bé" });
    assert.equal(joined.ok, true);
    assert.equal((await request(second, "room:start")).ok, false);
    assert.equal((await request(first, "room:start")).ok, false);
    await request(first, "room:ready"); await request(second, "room:ready");
    assert.equal((await request(first, "room:start")).ok, true);
    const room = game.rooms.get(hostSession.code)!;
    const drawerSocket = room.drawerId === hostSession.playerId ? first : second;
    const guesserSocket = drawerSocket === first ? second : first;
    const session = (drawerSocket === first ? created.session : joined.session) as Session;
    await request(first, "room:sync");
    await request(second, "room:sync");
    assert.equal(states.get(guesserSocket.id!)!.answer, null);
    assert.equal(states.get(drawerSocket.id!)!.answer, room.prompt!.answer);
    room.deadline = Date.now() - 1; room.tick();
    assert.equal((await request(guesserSocket, "draw:stroke", { id: "bad", width: 10, color: "#253447", points: [{ x: 1, y: 1 }] })).ok, false);
    assert.equal((await request(drawerSocket, "draw:stroke", { id: "bad", width: 10, color: "#253447", points: [{ x: Infinity, y: 1 }] })).ok, false);
    const received = new Promise(resolve => guesserSocket.once("draw:stroke", resolve));
    const stroke = { id: "first", width: 10, color: "#253447", points: [{ x: 1, y: 1 }, { x: 10, y: 12 }] };
    assert.equal((await request(drawerSocket, "draw:stroke", stroke)).ok, true);
    assert.deepEqual(await received, stroke);
    assert.equal((await request(guesserSocket, "guess:send", { text: "thử một câu" })).ok, true);
    await request(drawerSocket, "room:sync");
    assert.equal(states.get(drawerSocket.id!)!.guesses[0].text, "thử một câu");
    drawerSocket.disconnect();
    await new Promise(resolve => setTimeout(resolve, 30));
    const restored = await connect();
    let restoredView: RoomView | null = null;
    restored.on("room:state", (view: RoomView) => { restoredView = view; });
    assert.equal((await request(restored, "room:restore", { ...session, token: "00000000-0000-4000-8000-000000000000" })).ok, false);
    assert.equal((await request(restored, "room:restore", session)).ok, true);
    assert.equal((restoredView as RoomView | null)?.players.length, 2);
    assert.deepEqual((restoredView as RoomView | null)?.strokes, [stroke]);
    assert.equal(room.paused, false);
    const pending = room.guesses[0];
    assert.equal((await request(guesserSocket, "guess:judge", { guessId: pending.id, accepted: true })).ok, false);
    assert.equal((await request(restored, "guess:judge", { guessId: pending.id, accepted: true })).ok, true);
    assert.equal(room.phase, "result");
    assert.equal(room.results[0].accepted.length, 1);
    const attacker = await connect();
    assert.equal((await request(attacker, "guess:judge", { guessId: pending.id, accepted: true })).ok, false);
    assert.equal((await request(restored, "room:join", { code: room.code, name: "Trùng" })).ok, false);
    const resultId = room.results[0].id;
    assert.equal(room.deadline, 0);
    assert.equal((await request(restored, "turn:next", { resultId })).ok, false);
    assert.equal((await request(attacker, "turn:next", { resultId })).ok, false);
    assert.equal((await request(guesserSocket, "turn:next", {})).ok, false);
    assert.equal((await request(guesserSocket, "turn:next", { resultId: "00000000-0000-4000-8000-000000000000" })).ok, false);
    assert.equal((await request(guesserSocket, "turn:next", { resultId })).ok, true);
    assert.equal(room.phase, "preparing");
    await request(restored, "room:sync");
    assert.equal((restoredView as RoomView | null)?.phase, "preparing");
    assert.equal((await request(guesserSocket, "turn:next", { resultId })).ok, false);
  } finally {
    clients.forEach(client => client.disconnect());
    game.dispose();
    await new Promise<void>(resolve => server.close(() => resolve()));
  }
});
